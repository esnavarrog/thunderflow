  def self.regions
    REGIONS.map { |region| region[:name]}
  end

  def self.communes(name)
    return [] if name.blank?
    added_communes = CommunePrice.where(region_name: name).pluck(:commune)
    communes = AdministrativeAreas.communes_regions(name).reject { |commune| added_communes.include?(commune) }
    communes
  end

  def self.communes_regions(name)
    return [] if name.blank?
    region = REGIONS.find { |region| region[:name] == name }
    region ? region[:communes] : []
  end

